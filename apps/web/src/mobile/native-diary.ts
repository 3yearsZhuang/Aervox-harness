/** 日记在手机上的本地读写与按需生成。
 *
 * 生成能力来自共享包 @aervox/diary（与 API / Worker 同一份提示词与模板），
 * 发布沿用桌面端的协议：新建走「周期 + 版本 + outbox」一次性提交，改写保留历史版本。
 * 手机没有 Worker，所以定时链路不在这里；这里只做「取回今天」与「现在写一篇」。
 */
import { AervoxHttpError } from '@aervox/api-client';
import {
  DiaryGenerationService,
  generateDiaryId,
  localDateToday,
  todayWindow,
  type DiaryModelPort,
} from '@aervox/diary';
import type { IDiaryRepository, LocalContext } from '@aervox/repositories/diary';
import type { DiaryMaterialPort } from '@aervox/contracts';

const fail = (status: number, code: string): never => {
  throw new AervoxHttpError(status, 'native', { code, message: code });
};

/** 手机端没有后台任务：模板与非模型模式都要标明生成方式，展示时据此标注。 */
const TEMPLATE_MARKER = '（本篇为非 LLM 模式的模板日记';
const detectGeneratedBy = (content: string): 'llm' | 'template' =>
  content.includes(TEMPLATE_MARKER) ? 'template' : 'llm';

type DiaryRepoPort = Pick<
  IDiaryRepository,
  'getDiaryByDate' | 'listDiaries' | 'publishGeneratedDiary' | 'publishDiaryRevision'
>;

export interface DiaryRouteDeps {
  repo: DiaryRepoPort;
  materials: DiaryMaterialPort;
  ctx: LocalContext;
  /** 本机模型桥的一次补全；未配置模型时为 null，日记降级为模板并如实标注。 */
  model: DiaryModelPort | null;
  now?: () => Date;
}

export type DiaryRouteResult = { handled: true; result: unknown } | { handled: false };

export interface TodayDiaryResult {
  diaryId: string;
  localDate: string;
  title: string;
  content: string;
  mode: 'created' | 'rewritten' | 'existing';
  generatedBy: 'llm' | 'template';
  materialCount: number;
}

export function createDiaryRouteHandler({ repo, materials, ctx, model, now = () => new Date() }: DiaryRouteDeps) {
  const generation = new DiaryGenerationService({ materials, useModel: model !== null, model });

  /** 新建：草稿在事务外生成，发布时周期/版本/outbox 一次性落库（与桌面端同协议）。 */
  const createTodayDiary = async (localDate: string, focus?: string, styleId?: string) => {
    const draft = await generation.generate(ctx, { localDate, window: todayWindow(now()), focus, styleId });
    const cycleId = generateDiaryId('cyc');
    const { diary } = await repo.publishGeneratedDiary(ctx, {
      cycle: {
        id: cycleId,
        scheduleEpochId: `on_demand:${localDate}`,
        localDate,
        previousCutoffAt: todayWindow(now()).startIso,
        cutoffAt: todayWindow(now()).endIso,
      },
      diary: {
        id: generateDiaryId('diary'),
        localDate,
        title: draft.title,
        content: draft.content,
        autoGenerated: 1,
      },
      version: { id: generateDiaryId('dv'), perspective: 'ai_generated' },
      outboxEvent: {
        id: generateDiaryId('outbox'),
        eventType: 'diary.published',
        idempotencyKey: generateDiaryId('idem_diary'),
        payload: { cycleId, localDate, trigger: 'on_demand' },
      },
    } as Parameters<DiaryRepoPort['publishGeneratedDiary']>[1]);
    return { diaryId: diary.id, localDate, title: draft.title, content: draft.content,
      mode: 'created' as const, generatedBy: draft.generatedBy, materialCount: draft.materialCount };
  };

  /** 改写：新版本入账并推进主行，历史版本不覆盖。 */
  const rewriteTodayDiary = async (diaryId: string, localDate: string, focus?: string, styleId?: string) => {
    const draft = await generation.generate(ctx, { localDate, window: todayWindow(now()), focus, styleId });
    const versionId = generateDiaryId('dv');
    await repo.publishDiaryRevision(ctx, {
      diaryId,
      versionId,
      title: draft.title,
      content: draft.content,
      outboxId: generateDiaryId('outbox'),
    });
    return { diaryId, localDate, title: draft.title, content: draft.content,
      mode: 'rewritten' as const, generatedBy: draft.generatedBy, materialCount: draft.materialCount };
  };

  return async function handleDiaryRoute(method: string, url: URL, body: unknown): Promise<DiaryRouteResult> {
    const path = url.pathname;

    if (path === '/v1/diaries' && method === 'GET') {
      const localDate = url.searchParams.get('localDate');
      if (localDate) {
        const diary = await repo.getDiaryByDate(ctx, localDate);
        if (!diary) fail(404, 'DIARY_NOT_FOUND');
        return { handled: true, result: diary };
      }
      const parsedLimit = Number.parseInt(url.searchParams.get('limit') ?? '30', 10);
      const items = await repo.listDiaries(ctx, Number.isFinite(parsedLimit) ? Math.min(Math.max(parsedLimit, 1), 100) : 30);
      return { handled: true, result: { items } };
    }

    if (path === '/v1/diaries/generate-today' && method === 'POST') {
      const payload = (body ?? {}) as { rewrite?: boolean; focus?: string; styleId?: string };
      const localDate = localDateToday(now());
      const existing = await repo.getDiaryByDate(ctx, localDate);
      if (existing) {
        if (!payload.rewrite) {
          return { handled: true, result: { diaryId: existing.id, localDate, title: existing.title,
            content: existing.content, mode: 'existing', generatedBy: detectGeneratedBy(existing.content),
            materialCount: 0 } satisfies TodayDiaryResult };
        }
        return { handled: true, result: await rewriteTodayDiary(existing.id, localDate, payload.focus, payload.styleId) };
      }
      return { handled: true, result: await createTodayDiary(localDate, payload.focus, payload.styleId) };
    }

    return { handled: false };
  };
}
