import type { DiaryGenerationService } from "@aervox/diary";
import { generateDiaryId } from "@aervox/diary";
import type { LocalContext, IDiaryRepository } from "@aervox/repositories";

export interface DiaryPublicationInput {
  localDate: string;
  window: { startIso: string; endIso: string };
  scheduleEpochId: string;
  trigger: "scheduled" | "on_demand";
  focus?: string;
  styleId?: string;
  advance?: { scheduleId: string; nextRunAt: string; lastCutoffAt: string };
}

/** Generation runs outside the write transaction. Publication owns cycle, version, cursor and Outbox atomically. */
export async function publishGeneratedDiary(
  dependencies: { diaryRepo: Pick<IDiaryRepository, "publishGeneratedDiary">; generation: Pick<DiaryGenerationService, "generate"> },
  ctx: LocalContext,
  input: DiaryPublicationInput,
) {
  const draft = await dependencies.generation.generate(ctx, input);
  const cycleId = generateDiaryId("cyc");
  const published = await dependencies.diaryRepo.publishGeneratedDiary(ctx, {
    cycle: { id: cycleId, scheduleEpochId: input.scheduleEpochId, localDate: input.localDate,
      previousCutoffAt: input.window.startIso, cutoffAt: input.window.endIso },
    diary: { id: generateDiaryId("diary"), localDate: input.localDate, title: draft.title, content: draft.content, autoGenerated: 1 },
    version: { id: generateDiaryId("dv"), perspective: "ai_generated" },
    advance: input.advance,
    outboxEvent: { id: generateDiaryId("outbox"), eventType: "diary.published", idempotencyKey: generateDiaryId("idem_diary"),
      payload: { cycleId, localDate: input.localDate, trigger: input.trigger } },
  });
  return { ...published, draft };
}
