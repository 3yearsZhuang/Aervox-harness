import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { createInMemoryDatabase, initDatabaseSchema, SqliteDiaryRepository } from "../src/index.js";
const ctx = { workspaceId: "local", subjectUserId: "local" };
const publication = {
  cycle: { id: "cycle", scheduleEpochId: "daily", localDate: "2026-10-23", previousCutoffAt: "2026-10-22T16:00:00.000Z", cutoffAt: "2026-10-23T12:00:00.000Z" },
  diary: { id: "diary", localDate: "2026-10-23", title: "Title", content: "Generated content", autoGenerated: 1 },
  version: { id: "version", perspective: "ai_generated" },
  outboxEvent: { id: "event", eventType: "diary.published", idempotencyKey: "publication", payload: {} },
};
describe("generated diary publication is one transaction", () => {
  let database: Awaited<ReturnType<typeof createInMemoryDatabase>>;
  let repo: SqliteDiaryRepository;
  beforeEach(async () => { database = await createInMemoryDatabase(); await initDatabaseSchema(database.client); repo = new SqliteDiaryRepository(database.db); });
  afterEach(async () => { await database.cleanup(); });
  it("publishes cycle, diary, version and outbox together", async () => {
    const result = await repo.publishGeneratedDiary(ctx, publication);
    expect(result.cycle.status).toBe("Published");
    expect(result.cycle.diaryId).toBe("diary");
    for (const table of ["diary_cycles", "diaries", "diary_versions", "outbox_events"]) {
      const count = await database.client.execute(`SELECT count(*) n FROM ${table}`);
      expect(Number(count.rows[0]!.n)).toBe(1);
    }
  });
  it("a late cursor failure rolls back every publication row", async () => {
    await expect(repo.publishGeneratedDiary(ctx, { ...publication, advance: { scheduleId: "missing", nextRunAt: "2026-10-24T12:00:00.000Z", lastCutoffAt: publication.cycle.cutoffAt } })).rejects.toThrow("schedule missing");
    for (const table of ["diary_cycles", "diaries", "diary_versions", "outbox_events"]) {
      const count = await database.client.execute(`SELECT count(*) n FROM ${table}`);
      expect(Number(count.rows[0]!.n)).toBe(0);
    }
  });
  it("publishes a rewrite with its history and outbox, and rolls back on a late event collision", async () => {
    await repo.publishGeneratedDiary(ctx, publication);
    const rewrite = { diaryId: "diary", versionId: "rewrite", title: "Revised", content: "New content", outboxId: "revision-event" };
    const updated = await repo.publishDiaryRevision(ctx, rewrite);
    expect(updated.version).toBe(2);
    expect(updated.content).toBe("New content");
    await expect(repo.publishDiaryRevision(ctx, { ...rewrite, versionId: "failed-rewrite", content: "Must not commit" })).rejects.toThrow();
    const current = await repo.getDiaryByDate(ctx, publication.diary.localDate);
    expect(current?.version).toBe(2);
    expect(current?.content).toBe("New content");
    const versions = await database.client.execute("SELECT id FROM diary_versions ORDER BY id");
    expect(versions.rows.map(row => row.id)).toEqual(["rewrite", "version"]);
  });
});
