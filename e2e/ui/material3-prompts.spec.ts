import { test, expect } from './fixtures';

test.use({ platform: 'mobile' });

test('creates and deletes a model preset through nested modal prompts, with cancellation preserving data', async ({ page, servers }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto(servers.webUrl);
  await page.getByRole('button', { name: '打开设置', exact: true }).click();
  const settings = page.locator('md-dialog.mobile-settings-dialog');
  const create = settings.getByRole('button', { name: '新建预设', exact: true });
  await expect(create).toBeVisible();
  await create.click();
  const prompt = page.locator('md-dialog.avx-dialog-prompt').filter({ hasText: '新建模型预设' });
  await prompt.getByRole('textbox').fill('   ');
  await prompt.getByRole('button', { name: '创建', exact: true }).click();
  await expect(prompt).toContainText('名称不能为空');
  await prompt.getByRole('textbox').fill('审查修复的预设');
  await prompt.getByRole('textbox').press('Escape');
  await expect(prompt).toBeHidden();
  await expect(settings).toBeVisible();
  await expect(create).toBeFocused();
  await expect(settings.locator('.llm-preset-card').filter({ hasText: '审查修复的预设' })).toHaveCount(0);

  await create.click();
  await prompt.getByRole('textbox').fill('审查修复的预设');
  await prompt.getByRole('button', { name: '创建', exact: true }).click();
  await expect(prompt).toBeHidden();
  const card = settings.locator('.llm-preset-card').filter({ hasText: '审查修复的预设' });
  await expect(card).toBeVisible();
  await card.getByRole('button', { name: '删除', exact: true }).click();
  const confirm = page.locator('md-dialog.avx-dialog-prompt').filter({ hasText: '删除确认' });
  await confirm.getByRole('button', { name: '取消', exact: true }).click();
  await expect(confirm).toBeHidden();
  await expect(card).toBeVisible();
  await card.getByRole('button', { name: '删除', exact: true }).click();
  await confirm.getByRole('button', { name: '删除', exact: true }).click();
  await expect(confirm).toBeHidden();
  await expect(card).toHaveCount(0);
  await expect(settings).toBeVisible();
});

test('keeps sequential draft/delete confirmations above settings and Back cancels only the top prompt', async ({ page, servers }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.goto(servers.webUrl);
  await page.getByRole('button', { name: '打开设置', exact: true }).click();
  const settings = page.locator('md-dialog.mobile-settings-dialog');
  const prompts = page.locator('md-dialog.avx-dialog-prompt');
  await settings.getByRole('button', { name: '新建预设', exact: true }).click();
  await prompts.getByRole('textbox').fill('连续确认预设');
  await prompts.getByRole('button', { name: '创建', exact: true }).click();
  await expect(prompts).toHaveCount(0);
  const card = settings.locator('.llm-preset-card').filter({ hasText: '连续确认预设' });
  await expect(card).toBeVisible();
  const url = settings.getByRole('textbox', { name: '服务基址', exact: true });
  await url.fill('http://127.0.0.1:11435/v1');
  const discard = prompts.filter({ hasText: '切换模型预设' });
  const deletion = prompts.filter({ hasText: '删除确认' });
  const remove = card.getByRole('button', { name: '删除', exact: true });
  await remove.click();
  await discard.getByRole('button', { name: '放弃修改并继续', exact: true }).click();
  await deletion.getByRole('button', { name: '取消', exact: true }).click();
  await expect(prompts).toHaveCount(0);
  await expect(settings).toBeVisible();
  await expect(card).toBeVisible();
  await expect(remove).toBeFocused();
  await remove.click();
  await discard.getByRole('button', { name: '放弃修改并继续', exact: true }).click();
  await expect(deletion).toBeVisible();
  await page.evaluate(() => history.back());
  await expect(prompts).toHaveCount(0);
  await expect(settings).toBeVisible();
  await expect(card).toBeVisible();
  await expect(remove).toBeFocused();
  await expect(url).toHaveValue('http://127.0.0.1:11435/v1');
  await remove.click();
  await discard.getByRole('button', { name: '放弃修改并继续', exact: true }).click();
  await deletion.getByRole('button', { name: '删除', exact: true }).click();
  await expect(prompts).toHaveCount(0);
  await expect(card).toHaveCount(0);
  await expect(settings).toBeVisible();
});
