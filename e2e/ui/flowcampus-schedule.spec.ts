import { test, expect } from './fixtures';
import type { CampusStateSnapshot } from '../../plugins/plugins/tool/flowcampus/src/contracts/index.js';

test.use({ platform: 'mobile', loopProvider: 'replay' });
const statePath = '/v1/plugins/ap-tool-flowcampus/state';
test('weekly lessons and a reviewed CSV import persist without duplicate instances', async ({ page, request, servers }) => {
  const enabled = await request.patch(`${servers.apiUrl}/v1/plugins/ap-tool-flowcampus`, { data: { enabled: true } });
  expect(enabled.status()).toBe(200);
  const read = async (): Promise<CampusStateSnapshot> => {
    const response = await request.get(servers.apiUrl + statePath); expect(response.status()).toBe(200); return response.json();
  };
  const initial = await read();
  initial.state = { version: 1, places: [{ id: 'classroom', name: '教学楼', address: '' }], events: [], tasks: [], routes: [], settings: { originId: 'classroom', bufferMinutes: 5, timezone: 'Asia/Shanghai' } };
  expect((await request.put(servers.apiUrl + statePath, { data: { state: initial.state, expectedRevision: initial.revision, expectedLifecycleGeneration: initial.lifecycleGeneration } })).status()).toBe(200);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`${servers.webUrl}/?surface=proactive-ui`, { timeout: 90_000 });
  await page.getByRole('tab', { name: '切换到工具', exact: true }).click();
  await page.getByRole('navigation', { name: '首页入口' }).getByRole('button', { name: /^今日/ }).click();
  const today = page.locator('md-dialog[data-aria-label="今日"]');
  await expect(today).toBeVisible();
  const card = today.locator('.campus-home-card');
  await expect(card).toBeVisible({ timeout: 90_000 });
  await card.getByRole('button', { name: '查看与管理', exact: true }).click();
  const dialog = page.locator('.campus-dialog'); await expect(dialog).toBeVisible();
  await dialog.getByRole('button', { name: '课表与日程', exact: true }).click();
  await dialog.getByRole('button', { name: '新增周课程', exact: true }).click();
  await dialog.getByLabel('周课程名称', { exact: true }).fill('每周线性代数');
  await dialog.getByRole('combobox', { name: '周课程地点', exact: true }).selectOption('classroom');
  await dialog.getByLabel('起始日期', { exact: true }).fill('2026-10-26');
  await dialog.getByLabel('截止日期', { exact: true }).fill('2026-11-23');
  const weekdays = dialog.locator('.campus-weekly-editor fieldset input');
  for (let index = 0; index < 7; index++) await weekdays.nth(index).setChecked(index === 0);
  const saved = page.waitForResponse(response => response.url().endsWith(statePath) && response.request().method() === 'PUT');
  await dialog.getByRole('button', { name: '保存课程系列', exact: true }).click(); expect((await saved).status()).toBe(200);
  await dialog.getByLabel('查看课程所在周', { exact: true }).fill('2026-10-26');
  await expect(dialog.locator('.campus-occurrences li')).toHaveCount(1);
  await dialog.getByRole('button', { name: '本次已到达', exact: true }).click();
  await expect.poll(async () => (await read()).state.occurrenceOverrides?.[0]?.status).toBe('arrived');
  expect((await read()).state.recurrences?.[0]?.status).toBe('scheduled');
  await dialog.getByRole('button', { name: '导入课表', exact: true }).click();
  const importer = page.locator('.campus-import-dialog'); await expect(importer).toBeVisible();
  await importer.getByLabel('文件内容', { exact: true }).fill('uid,title,place,start_at,end_at\ncourse-csv,导入的课程,教学楼,2026-11-04T08:30:00+08:00,2026-11-04T10:00:00+08:00');
  await importer.getByRole('button', { name: '生成导入预览', exact: true }).click();
  await expect(importer).toContainText('导入的课程'); expect((await read()).state.events).toHaveLength(0);
  await importer.getByRole('button', { name: '确认导入 1 条', exact: true }).click();
  await expect(importer).not.toBeVisible(); expect((await read()).state.events).toHaveLength(1);
  await dialog.getByRole('button', { name: '导入课表', exact: true }).click();
  await importer.getByRole('button', { name: '生成导入预览', exact: true }).click();
  await expect(importer).toContainText('完全重复，不再写入');
  await expect(importer.getByRole('button', { name: '确认导入 0 条', exact: true })).toBeDisabled();
  expect((await read()).state.events).toHaveLength(1);
});
